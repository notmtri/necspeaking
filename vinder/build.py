#!/usr/bin/env python3
"""Build the shareable versions of Vinder from index.html, mobile.html, src/ and assets/.

    vinder.html          web version, one self-contained file (phone frame on desktop)
    vinder-mobile.html   mobile version, one self-contained file
    mobile/              mobile version as an installable app: index.html, manifest,
                         offline service worker and icons; host this folder over HTTPS

Run from anywhere:  python3 vinder/build.py
"""
import base64
import hashlib
import json
import pathlib
import re
import shutil
import sys

ROOT = pathlib.Path(__file__).resolve().parent
MIME = {'.webp': 'image/webp', '.png': 'image/png', '.jpg': 'image/jpeg', '.woff2': 'font/woff2'}
ASSET = re.compile(r'(?:\.\./)?assets/[\w./-]+\.(?:webp|png|jpg|woff2)')
CSS_LINK = re.compile(r'<link rel="stylesheet" href="src/([\w-]+\.css)">')
SCRIPT = re.compile(r'<script src="src/([\w-]+\.js)"></script>')
MANIFEST_LINK = re.compile(r'<link rel="manifest" href="manifest\.webmanifest">\n?')
ICONS = ['icon-192.png', 'icon-512.png', 'maskable-512.png', 'apple-touch-icon.png']

SERVICE_WORKER = """/* Vinder offline cache. Generated by build.py; the version changes whenever the app does. */
const CACHE = 'vinder-%(version)s';
const FILES = %(files)s;
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', e => {
  e.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(k => k.startsWith('vinder-') && k !== CACHE).map(k => caches.delete(k))))
    .then(() => self.clients.claim()));
});
self.addEventListener('fetch', e => {
  const req = e.request, url = new URL(req.url);
  // Only the app itself is cached; Gemini calls and links out go straight to the network.
  if (req.method !== 'GET' || url.origin !== self.location.origin) return;
  e.respondWith(caches.match(req, { ignoreSearch: true }).then(hit => hit || fetch(req).then(res => {
    if (res.ok && res.type === 'basic') { const copy = res.clone(); caches.open(CACHE).then(c => c.put(req, copy)); }
    return res;
  }).catch(() => (req.mode === 'navigate' ? caches.match('./index.html') : Response.error()))));
});
"""


def read(rel):
    return (ROOT / rel).read_text(encoding='utf-8')


def inline_code(html):
    html = CSS_LINK.sub(lambda m: '<style>\n' + read('src/' + m.group(1)) + '\n</style>', html)

    def script(m):
        code = read('src/' + m.group(1))
        if '</script' in code:
            sys.exit(f'src/{m.group(1)} contains "</script", which would end the inline script early')
        return '<script>\n' + code + '\n</script>'

    html = SCRIPT.sub(script, html)
    if 'src="src/' in html or 'href="src/' in html:
        sys.exit('an external src/ reference was left in the output')
    return html


def inline_assets(html, keep_icons=False):
    seen = {}
    for m in ASSET.finditer(html):
        key = m.group(0).replace('../', '', 1)
        if keep_icons and key.startswith('assets/icons/'):
            continue
        seen[key] = seen.get(key, 0) + 1
        if not (ROOT / key).exists():
            sys.exit(f'missing asset: {key}')
    for key, n in seen.items():
        if n > 1:
            print(f'warning: {key} is referenced {n} times and will be embedded {n} times', file=sys.stderr)

    def repl(m):
        key = m.group(0).replace('../', '', 1)
        if keep_icons and key.startswith('assets/icons/'):
            return key.replace('assets/icons/', 'icons/')
        path = ROOT / key
        return f'data:{MIME[path.suffix]};base64,{base64.b64encode(path.read_bytes()).decode()}'

    return ASSET.sub(repl, html), len(seen)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
    return path


def report(path, extra=''):
    print(f'wrote {path.relative_to(ROOT.parent)} ({path.stat().st_size / 1024:.0f} KB{extra})')


def main():
    # Web: one file.
    html, n = inline_assets(inline_code(read('index.html')))
    report(write(ROOT / 'vinder.html', html), f', {n} assets inlined')

    mobile = inline_code(read('mobile.html'))

    # Mobile: one file. A manifest can't travel inside a single file, so it is left out;
    # the Apple touch icon is inlined so "Add to Home Screen" still gets the logo.
    html, n = inline_assets(MANIFEST_LINK.sub('', mobile))
    report(write(ROOT / 'vinder-mobile.html', html), f', {n} assets inlined')

    # Mobile: installable folder.
    out = ROOT / 'mobile'
    if out.exists():
        shutil.rmtree(out)
    html, n = inline_assets(mobile, keep_icons=True)
    index = write(out / 'index.html', html)
    manifest = json.loads(read('manifest.webmanifest'))
    for icon in manifest['icons']:
        icon['src'] = icon['src'].replace('assets/icons/', 'icons/')
    write(out / 'manifest.webmanifest', json.dumps(manifest, indent=2) + '\n')
    for name in ICONS:
        (out / 'icons').mkdir(exist_ok=True)
        shutil.copyfile(ROOT / 'assets' / 'icons' / name, out / 'icons' / name)
    files = ['./', './index.html', './manifest.webmanifest'] + [f'./icons/{name}' for name in ICONS]
    version = hashlib.sha1((html + json.dumps(manifest)).encode()).hexdigest()[:10]
    write(out / 'sw.js', SERVICE_WORKER % {'version': version, 'files': json.dumps(files)})
    report(index, f', {n} assets inlined, plus manifest, service worker {version} and {len(ICONS)} icons')


if __name__ == '__main__':
    main()
